#!/usr/bin/env bash
# Project-local single-node Apache Kafka (KRaft, broker+controller in one JVM) for the Kafka profile.
# Everything lives under <repo>/.local (gitignored); nothing is installed system-wide.
#
#   scripts/kafka.sh fetch     download the binary tarball + .sha512, verify SHA-512, extract
#   scripts/kafka.sh up        fetch if needed, format storage once, start, wait until ready, create topics
#   scripts/kafka.sh down      stop the broker (SIGTERM, then SIGKILL after 30 s) and confirm it is gone
#   scripts/kafka.sh status    pid, port, RSS of the broker JVM
#   scripts/kafka.sh reset     down + delete the data dir (all topics, offsets, cluster id)
#   scripts/kafka.sh topics    create events.raw/events.resolved/events.failed (idempotent) and describe them
#   scripts/kafka.sh purge     delete every topic except the three canonical ones (test namespaces)
#
# Env: KAFKA_VERSION (default 4.3.1), TRANSITOS_JAVA_HOME (JDK to run Kafka with; default: java_home),
#      KAFKA_HEAP_OPTS (default -Xmx512m -Xms256m).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KAFKA_VERSION="${KAFKA_VERSION:-4.3.1}"
SCALA_VERSION="2.13"
DIST="kafka_${SCALA_VERSION}-${KAFKA_VERSION}"
LOCAL="$ROOT/.local"
KDIR="$LOCAL/kafka"
KHOME="$KDIR/$DIST"
DATA="$LOCAL/kafka-data"
LOGS="$LOCAL/kafka-logs"
CONF="$KDIR/server.properties"
PIDFILE="$KDIR/kafka.pid"
BOOTSTRAP="127.0.0.1:9092"
TOPICS=(events.raw events.resolved events.failed)
RETENTION_MS=604800000   # 7 days

export JAVA_HOME="${TRANSITOS_JAVA_HOME:-${JAVA_HOME:-$(/usr/libexec/java_home 2>/dev/null || true)}}"
export KAFKA_HEAP_OPTS="${KAFKA_HEAP_OPTS:--Xmx512m -Xms256m}"
export LOG_DIR="$LOGS"
# no remote JMX: the default opens an RMI listener on a random port on all interfaces
export KAFKA_JMX_OPTS="${KAFKA_JMX_OPTS:--Djava.awt.headless=true}"  # any non-empty value; the JDK agent starts if jmxremote is set at all
# CLI tools (kafka-topics.sh, kafka-storage.sh) get a small heap of their own
CLI_HEAP="-Xmx128m -Xms32m"

log() { printf '[kafka] %s\n' "$*" >&2; }

fetch() {
  if [[ -x "$KHOME/bin/kafka-server-start.sh" ]]; then return 0; fi
  local dl="$KDIR/download" base
  mkdir -p "$KDIR"
  rm -rf "$dl"; mkdir -p "$dl"
  for base in "https://downloads.apache.org/kafka/$KAFKA_VERSION" "https://archive.apache.org/dist/kafka/$KAFKA_VERSION"; do
    log "downloading $DIST.tgz from $base"
    if curl -fsSL -o "$dl/$DIST.tgz" "$base/$DIST.tgz" && curl -fsSL -o "$dl/$DIST.tgz.sha512" "$base/$DIST.tgz.sha512"; then
      break
    fi
  done
  [[ -s "$dl/$DIST.tgz" && -s "$dl/$DIST.tgz.sha512" ]] || { log "download failed"; exit 1; }
  # Apache publishes `gpg --print-md SHA512` format: "<file>: HEX HEX ..." over several lines
  local want got
  want="$(sed -e "s/^.*$DIST.tgz://" "$dl/$DIST.tgz.sha512" | tr -d ' \t\r\n' | tr 'A-F' 'a-f')"
  got="$(shasum -a 512 "$dl/$DIST.tgz" | awk '{print $1}')"
  if [[ ${#want} -ne 128 || "$want" != "$got" ]]; then
    log "SHA-512 MISMATCH: published=$want computed=$got"; rm -rf "$dl"; exit 1
  fi
  log "SHA-512 verified: $got"
  printf '%s  %s\n' "$got" "$DIST.tgz" > "$KDIR/$DIST.tgz.sha512.verified"
  tar -xzf "$dl/$DIST.tgz" -C "$KDIR"
  rm -rf "$dl"
}

write_conf() {
  mkdir -p "$DATA" "$LOGS"
  cat > "$CONF" <<EOF
# generated by scripts/kafka.sh - single node, localhost only
process.roles=broker,controller
node.id=1
controller.quorum.voters=1@127.0.0.1:9093
listeners=PLAINTEXT://127.0.0.1:9092,CONTROLLER://127.0.0.1:9093
advertised.listeners=PLAINTEXT://127.0.0.1:9092
controller.listener.names=CONTROLLER
inter.broker.listener.name=PLAINTEXT
listener.security.protocol.map=CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT
log.dirs=$DATA
num.partitions=3
default.replication.factor=1
min.insync.replicas=1
auto.create.topics.enable=false
log.retention.ms=$RETENTION_MS
log.index.size.max.bytes=1048576
offsets.topic.replication.factor=1
offsets.topic.num.partitions=10
transaction.state.log.replication.factor=1
transaction.state.log.min.isr=1
share.coordinator.state.topic.replication.factor=1
share.coordinator.state.topic.min.isr=1
group.initial.rebalance.delay.ms=0
num.network.threads=2
num.io.threads=4
num.recovery.threads.per.data.dir=1
EOF
}

pid() { [[ -f "$PIDFILE" ]] && cat "$PIDFILE" || true; }
alive() { local p; p="$(pid)"; [[ -n "$p" ]] && kill -0 "$p" 2>/dev/null; }
port_open() { nc -z 127.0.0.1 9092 >/dev/null 2>&1; }

kt() { KAFKA_HEAP_OPTS="$CLI_HEAP" "$KHOME/bin/kafka-topics.sh" --bootstrap-server "$BOOTSTRAP" "$@"; }

up() {
  fetch
  if alive; then log "already running (pid $(pid))"; return 0; fi
  if port_open; then log "port 9092 is taken by another process; refusing to start"; exit 1; fi
  write_conf
  if [[ ! -f "$DATA/meta.properties" ]]; then
    local cid
    cid="$(KAFKA_HEAP_OPTS="$CLI_HEAP" "$KHOME/bin/kafka-storage.sh" random-uuid)"
    KAFKA_HEAP_OPTS="$CLI_HEAP" "$KHOME/bin/kafka-storage.sh" format -t "$cid" -c "$CONF" >&2
  fi
  local t0 t1
  t0="$(python3 -c 'import time;print(time.time())')"
  log "starting Kafka $KAFKA_VERSION with $("$JAVA_HOME/bin/java" -version 2>&1 | head -1) heap: $KAFKA_HEAP_OPTS"
  nohup "$KHOME/bin/kafka-server-start.sh" "$CONF" > "$LOGS/stdout.log" 2>&1 &
  echo $! > "$PIDFILE"
  for _ in $(seq 1 120); do
    if ! alive; then log "broker exited during startup; tail of log:"; tail -40 "$LOGS/stdout.log" >&2; exit 1; fi
    if grep -q "Kafka Server started" "$LOGS/stdout.log" 2>/dev/null && port_open; then break; fi
    sleep 0.5
  done
  port_open || { log "broker did not become ready in 60 s"; down; exit 1; }
  t1="$(python3 -c 'import time;print(time.time())')"
  log "ready in $(python3 -c "print(round($t1-$t0,1))") s (pid $(pid))"
  topics
}

down() {
  local p; p="$(pid)"
  if [[ -z "$p" ]] || ! kill -0 "$p" 2>/dev/null; then log "not running"; rm -f "$PIDFILE"; return 0; fi
  kill "$p"
  for _ in $(seq 1 60); do kill -0 "$p" 2>/dev/null || break; sleep 0.5; done
  if kill -0 "$p" 2>/dev/null; then log "SIGTERM timed out; SIGKILL"; kill -9 "$p"; sleep 1; fi
  rm -f "$PIDFILE"
  if kill -0 "$p" 2>/dev/null; then log "pid $p still alive"; exit 1; fi
  log "stopped (pid $p)"
}

status() {
  if alive; then
    local p rss; p="$(pid)"; rss="$(ps -o rss= -p "$p" | tr -d ' ')"
    echo "running pid=$p rss=$((rss / 1024))MB port9092=$(port_open && echo open || echo closed) version=$KAFKA_VERSION"
  else
    echo "stopped"; return 3
  fi
}

reset() { down; rm -rf "$DATA" "$LOGS"; log "data dir removed"; }

topics() {
  local t
  for t in "${TOPICS[@]}"; do
    kt --create --if-not-exists --topic "$t" --partitions 3 --replication-factor 1 \
       --config retention.ms="$RETENTION_MS" >/dev/null
  done
  kt --describe --topic 'events\.(raw|resolved|failed)'
}

purge() {   # one batched AdminClient call (a kafka-topics.sh JVM per topic is far too slow)
  (cd "$ROOT" && uv run --extra kafka python -m transitos.plumbing.kafka_local purge)
}

case "${1:-}" in
  fetch) fetch ;; up) up ;; down) down ;; status) status ;; reset) reset ;; topics) topics ;; purge) purge ;;
  *) echo "usage: $0 fetch|up|down|status|reset|topics|purge" >&2; exit 2 ;;
esac
